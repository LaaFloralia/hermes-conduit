export const skillMetadata = Object.freeze(Object.fromEntries(Object.entries(groups).flatMap(([category, skills]) =>
  Object.entries(skills).map(([name, [summary, detail]]) => [name, Object.freeze({ category, summary, detail })]))));
export function describeSkill(name, description) {
  return Object.hasOwn(skillMetadata, name) ? { ...skillMetadata[name], metadataKnown: true }
    : { category: 'その他', summary: description, detail: description, metadataKnown: false };
}
export function unregisteredSkills(items) {
  return [...new Set(items.filter(item => !Object.hasOwn(skillMetadata, item.name)).map(item => item.name))].sort();
}
