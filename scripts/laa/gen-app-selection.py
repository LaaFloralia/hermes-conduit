#!/usr/bin/env python3
"""Generate Conduit/LAA/Design/LAAAppSelectionTokens.swift from tokens.json appSelection.

The model/effort selection's look (方針A「大理石の脈」) lives in one place,
hq/design/tokens.json `appSelection`. Swift reads only this generated file.

    python3 scripts/laa/gen-app-selection.py [--tokens ~/hq/design/tokens.json] [--check]
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "Conduit/LAA/Design/LAAAppSelectionTokens.swift")


def num(v):
    return repr(float(v))


def rgb(v):
    return f".init(r: {num(v[0])}, g: {num(v[1])}, b: {num(v[2])})"


def pair(d):
    return f"Pair(dark: {num(d['dark'])}, light: {num(d['light'])})"


def hex_rgb(value):
    value = value.lstrip("#")
    return [round(int(value[i:i + 2], 16) / 255, 3) for i in (0, 2, 4)]


def neon_model(tokens):
    """Gemini 4 Neon's finish (2026-11-23). `appSelection.models.neon` wins
    once hq/design adopts one; until then it is composed only of existing
    values: the house 青緑 from `color.role` for its colour and light, and the
    second tier's strength, scale and speed (Astra's), so it reads apart from
    Mythos's violet without a new HEX."""
    sel = tokens["appSelection"]
    if "neon" in sel["models"]:
        return sel["models"]["neon"]
    light, dark = tokens["color"]["role"]["light"], tokens["color"]["role"]["dark"]["app"]
    tier = sel["models"]["astra"]
    return {
        "strength": tier["strength"], "tileScale": tier["tileScale"], "speed": tier["speed"],
        "body": {"dark": {"top": hex_rgb(dark["accentFill"]), "bottom": hex_rgb(dark["bg"])},
                 "light": {"top": hex_rgb(light["selection"]["value"]), "bottom": hex_rgb(dark["accent"])}},
        "ink": {"dark": hex_rgb(dark["accent"]), "light": hex_rgb(light["accent"]["value"])},
        "lightColor": {"dark": hex_rgb(dark["text"]), "light": hex_rgb(light["surface"]["value"])},
        "glow": hex_rgb(dark["accent"]),
    }


def render(sel, neon):
    m, st, g, p, li, se = dict(sel["models"], neon=neon), sel["steps"], sel["glass"], sel["pattern"], sel["light"], sel["selection"]
    lines = [
        "// Generated by scripts/laa/gen-app-selection.py from hq/design/tokens.json appSelection.",
        "// Do not edit: change tokens.json and run the script again.",
        "#if LAA_BUILD",
        "import CoreGraphics",
        "",
        "enum LAAAppSelectionTokens {",
        "    struct RGB: Equatable { let r: Double, g: Double, b: Double }",
        "    struct Pair: Equatable {",
        "        let dark: Double, light: Double",
        "        func value(dark isDark: Bool) -> Double { isDark ? dark : light }",
        "    }",
        "    struct Duo: Equatable {",
        "        let dark: RGB, light: RGB",
        "        func value(dark isDark: Bool) -> RGB { isDark ? dark : light }",
        "    }",
        "    struct Model: Equatable {",
        "        let strength: Double, tileScale: Double, speed: Double",
        "        let bodyTop: Duo, bodyBottom: Duo, ink: Duo, lightColor: Duo, glow: RGB",
        "    }",
        "    struct Step: Equatable { let intensity: Double, tileScale: Double, hair: Double, speed: Double }",
        "",
    ]
    for key in ("mythos", "astra", "fable", "neon", "stone"):
        t = m[key]
        b = t["body"]
        lines.append(
            f"    static let {key} = Model(strength: {num(t['strength'])}, tileScale: {num(t['tileScale'])}, speed: {num(t['speed'])},\n"
            f"        bodyTop: .init(dark: {rgb(b['dark']['top'])}, light: {rgb(b['light']['top'])}),\n"
            f"        bodyBottom: .init(dark: {rgb(b['dark']['bottom'])}, light: {rgb(b['light']['bottom'])}),\n"
            f"        ink: .init(dark: {rgb(t['ink']['dark'])}, light: {rgb(t['ink']['light'])}),\n"
            f"        lightColor: .init(dark: {rgb(t['lightColor']['dark'])}, light: {rgb(t['lightColor']['light'])}),\n"
            f"        glow: {rgb(t['glow'])})"
        )
    lines.append("")
    for key in ("plain", "model", "xhigh", "max", "ultracode"):
        s = st[key]
        lines.append(
            f"    static let {key}Step = Step(intensity: {num(s['intensity'])}, tileScale: {num(s.get('tileScale', 1))}, "
            f"hair: {num(s.get('hair', 1))}, speed: {num(s.get('speed', 1))})"
        )
    op = p["opacity"]
    lb = p["labelBand"]
    tg, bd, rl = g["topGloss"], g["bottomDepth"], g["rimLight"]
    sh, bs = li["sheen"], li["bandShoulder"]
    lines += [
        "",
        f"    static let bodyOpacity = {pair(g['bodyOpacity'])}",
        f"    static let topGloss = {pair(tg)}",
        f"    static let topGlossHeightRatio: CGFloat = {num(tg['heightRatio'])}",
        f"    static let topGlossInsetPt: CGFloat = {num(tg['insetPt'])}",
        f"    static let bottomDepth = {pair(bd)}",
        f"    static let bottomDepthRadiusPt: CGFloat = {num(bd['radiusPt'])}",
        f"    static let rimLight = {pair(rl)}",
        f"    static let glowOpacity = {pair(g['glowOpacity'])}",
        f"    static let glowRadiusPt: CGFloat = {num(g['glowRadiusPt'])}",
        f"    static let glowOffsetPt: CGFloat = {num(g['glowOffsetPt'])}",
        "",
        f"    static let tilePt = CGSize(width: {num(p['tilePt'][0])}, height: {num(p['tilePt'][1])})",
        f"    static let assetCloud = {json.dumps(p['assets']['cloud'])}",
        f"    static let assetMain = {json.dumps(p['assets']['main'])}",
        f"    static let assetHair = {json.dumps(p['assets']['hair'])}",
        f"    static let cloudOpacity = Pair(dark: {num(op['dark']['cloud'])}, light: {num(op['light']['cloud'])})",
        f"    static let mainOpacity = Pair(dark: {num(op['dark']['main'])}, light: {num(op['light']['main'])})",
        f"    static let hairOpacity = Pair(dark: {num(op['dark']['hair'])}, light: {num(op['light']['hair'])})",
        f"    static let labelBandMiddle = {num(lb['middleOpacity'])}",
        f"    static let labelBandStops: [Double] = [{', '.join(num(x) for x in lb['stops'])}]",
        f"    static let labelBandChevron = {num(lb['chevronOpacity'])}",
        f"    static let labelBandChevronSpanPt: (from: CGFloat, to: CGFloat) = ({num(lb['chevronSpanPt'][0])}, {num(lb['chevronSpanPt'][1])})",
        "",
        f"    static let bandWidthRatio: CGFloat = {num(li['bandWidthRatio'])}",
        f"    static let bandShoulderAt = {num(bs['at'])}",
        f"    static let bandShoulderShare = {num(bs['share'])}",
        f"    static let lightPeak = {pair(li['peak'])}",
        f"    static let sheen = {pair(sh)}",
        f"    static let sheenWidthRatio: CGFloat = {num(sh['widthRatio'])}",
        f"    static let sheenAngleDeg = {num(sh['angleDeg'])}",
        f"    static let secondsPerCrossing = {num(li['secondsPerCrossing'])}",
        f"    static let travel: (from: Double, to: Double) = ({num(li['travel'][0])}, {num(li['travel'][1])})",
        f"    static let autoreverse = {'true' if li['autoreverse'] else 'false'}",
        f"    static let maxFrameRate: Float = {num(li['maxFrameRate'])}",
        f"    static let restPosition = {num(li['restPosition'])}",
        "",
        f"    static let selectionSeconds = {num(se['durationMs'] / 1000)}",
        f"    static let frontFrom = {num(se['frontFrom'])}",
        f"    static let frontTo = {num(se['frontTo'])}",
        f"    static let frontWidthRatio = {num(se['frontWidthRatio'])}",
        "}",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tokens", default=os.path.expanduser("~/hq/design/tokens.json"))
    ap.add_argument("--check", action="store_true", help="fail if the committed file differs")
    args = ap.parse_args()
    with open(args.tokens, encoding="utf-8") as f:
        tokens = json.load(f)
    sel = tokens["appSelection"]
    if sel["light"].get("easing") != "easeInEaseOut" or sel["selection"].get("easing") != "state":
        sys.exit("appSelection easing changed: update LAACeremony.swift by hand")
    text = render(sel, neon_model(tokens))
    if args.check:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                sys.exit(f"{OUT} is stale: run scripts/laa/gen-app-selection.py")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(OUT)


if __name__ == "__main__":
    main()
